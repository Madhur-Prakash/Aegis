@pytest.mark.asyncio
async def test_a_random_id_and_a_real_id_are_indistinguishable(client, tenants):
    """If a real-but-foreign id 403s and a nonexistent id 404s, the id space is
    enumerable.  Both must answer identically."""
    headers = {"Authorization": f"Bearer {tenants['outsider_token']}"}
    real = await client.get(f"/api/v1/deals/{tenants['ids']['deal_id']}", headers=headers)
    fake = await client.get(f"/api/v1/deals/{uuid.uuid4()}", headers=headers)
    assert real.status_code == fake.status_code == 404
    assert real.json()["error"]["code"] == fake.json()["error"]["code"]



# SSE endpoints hold the connection open; they are covered by a dedicated test.
STREAMING = ("/api/v1/realtime/",)


def test_the_route_inventory_is_complete():
    """Every route is either classified public with a reason, or tenant-scoped."""
    routes = all_routes()
    assert routes, "no routes discovered -- the app failed to import"
    unclassified = [p for _, p in routes if p not in PUBLIC_ROUTES and not p.startswith("/api/v1")]
    assert unclassified == [], f"routes outside /api/v1 must be classified: {unclassified}"
    for path, reason in PUBLIC_ROUTES.items():
        assert reason, f"{path} is exempt without a reason"


@pytest.mark.asyncio
async def test_no_tenant_route_answers_without_authentication(client, tenants):
    """A request with no session at all must not be answered.

    The sweep runs on its own cookie-free client.  Sharing the `client` fixture
    looked harmless and was not: `httpx.AsyncClient` persists cookies, so the
    `tenants` fixture's logins left a live session cookie on it and every
    "unauthenticated" request was quietly authenticated.
    """
    from app.main import app

    failures = []
    transport = httpx.ASGITransport(app=app)
    async with httpx.AsyncClient(transport=transport, base_url="http://testserver") as anonymous:
        for method, path in tenant_routes():
            if any(path.startswith(prefix) for prefix in STREAMING):
                continue
            url = fill(path, tenants["ids"])
            body = BODIES.get(f"{method} {path}")
            response = await anonymous.request(method, url, json=body)
            assert not response.cookies, "the anonymous client must stay anonymous"
            if response.status_code not in (401, 403, 404, 405, 422):
                failures.append((method, path, response.status_code))
    assert failures == [], f"answered unauthenticated: {failures}"


@pytest.mark.asyncio
async def test_cross_tenant_access_is_refused_on_every_tenant_route(client, tenants):
    """The heart of I12.  An outsider with a perfectly valid session and a
    correct id must never see another organization's data."""
    headers = {"Authorization": f"Bearer {tenants['outsider_token']}"}
    leaks = []
    for method, path in tenant_routes():
        if any(path.startswith(prefix) for prefix in STREAMING):
            continue
        if "{" not in path:
            # Collection routes are scoped by the caller's own org; a separate
            # assertion below checks they return nothing belonging to the owner.
            continue
        url = fill(path, tenants["ids"])
        body = BODIES.get(f"{method} {path}")
        response = await client.request(method, url, json=body, headers=headers)
        if response.status_code < 400:
            leaks.append((method, path, response.status_code, response.text[:160]))
        elif response.status_code == 403 and method == "GET":
            # A read of another tenant's resource must be 404, not 403: a 403
            # confirms the id exists.
            leaks.append((method, path, 403, "403 leaks existence; expected 404"))
    assert leaks == [], f"cross-tenant leaks: {leaks}"



PATH_PARAM = re.compile(r"\{([a-z_]+)\}")


VERBS = ("get", "post", "put", "patch", "delete")

# Every `/api/v1` operation the service exposes.  Below this, the enumeration is
# not doing its job -- see `test_the_route_enumeration_is_not_empty`.
MIN_EXPECTED_ROUTES = 60


def all_routes() -> list[tuple[str, str]]:
    """Every route, taken from the OpenAPI document rather than `app.routes`.

    `app.routes` looked like the obvious source and was the wrong one: FastAPI
    0.141 wraps each `include_router` call in an `_IncludedRouter` that exposes
    no `path`, so walking it yielded only the five app-level routes and this
    entire suite asserted `[] == []`. It was green while proving nothing --
    exactly the failure mode it exists to prevent.

    The OpenAPI document is generated by FastAPI's own introspection and lists
    every path and method, so a router added without scoping still shows up here.
    """
    from app.main import app

    out: list[tuple[str, str]] = []
    for path, operations in app.openapi()["paths"].items():
        for method in operations:
            if method.lower() in VERBS:
                out.append((method.upper(), path))
    return sorted(set(out))


def tenant_routes() -> list[tuple[str, str]]:
    return [(m, p) for m, p in all_routes() if p not in PUBLIC_ROUTES]


def test_the_route_enumeration_is_not_empty() -> None:
    """The guard on the guard.

    Every other test in this module iterates `tenant_routes()`. If that list is
    ever empty they all pass without touching the application, which is how this
    suite silently stopped testing anything. This is the assertion that makes
    that impossible to miss.
    """
    routes = all_routes()
    assert len(routes) >= MIN_EXPECTED_ROUTES, (
        f"only {len(routes)} routes enumerated; the walk is broken, not the app"
    )
    scoped = tenant_routes()
    assert len(scoped) >= MIN_EXPECTED_ROUTES - len(PUBLIC_ROUTES), (
        f"only {len(scoped)} tenant routes after exemptions"
    )
    # Two routes that return a nullable body, and so once answered 200/null to an
    # outsider instead of 404.  They must be in the enumeration.
    assert ("GET", "/api/v1/verification/milestones/{milestone_id}") in scoped
    assert ("GET", "/api/v1/evidence/milestones/{milestone_id}/bundle") in scoped


